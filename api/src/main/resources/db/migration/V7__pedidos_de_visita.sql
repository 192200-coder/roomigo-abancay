-- V7: pedidos de visita para publicaciones en venta.
-- En venta no se reserva ni se paga por la plataforma: el interesado propone una fecha
-- y el propietario la confirma o la declina (ambos reciben notificaciones).

CREATE TABLE public.visit_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES public.rooms (id) ON DELETE CASCADE,
    requester_id bigint NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    preferred_date date NOT NULL,
    preferred_time time without time zone,
    contact_phone varchar(20),
    message text,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    owner_note varchar(300),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT visit_requests_status_check
        CHECK (status IN ('PENDING', 'CONFIRMED', 'DECLINED', 'CANCELLED'))
);

CREATE INDEX idx_visit_requests_room ON public.visit_requests (room_id);
CREATE INDEX idx_visit_requests_requester ON public.visit_requests (requester_id);
